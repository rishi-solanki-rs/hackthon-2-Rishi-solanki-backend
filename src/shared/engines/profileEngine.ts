import { User } from '../types/user';
import { Listing } from '../types/listing';
import { Request } from '../types/request';

export type BadgeName = 'founding-lender' | 'helper' | 'toolkeeper' | 'reliable' | 'neighbour-of-month' | 'thank-you';

export interface ProfileBadge {
  name: BadgeName;
  earned: boolean;
  rule: string;
}

export interface UserProfileStats {
  itemsShared: number;
  activeListings: number;
  completedBorrows: number;
  thankYouNotes: number;
}

export interface UserProfileSummary {
  stats: UserProfileStats;
  badges: ProfileBadge[];
}

// Thresholds from the Detailed Design, section 10 (editable settings)
export const BADGE_THRESHOLDS = {
  foundingLenders: 10,
  helperCompletedLoans: 5,
  toolkeeperListedItems: 5,
  reliableCompletedBorrows: 3,
};

/**
 * Deterministic reputation counters and badges. Never generated by AI.
 */
export function computeUserProfile(user: User, users: User[], listings: Listing[], requests: Request[]): UserProfileSummary {
  const ownListings = listings.filter((l) => l.ownerId === user.id && l.status !== 'closed' && l.moderationStatus !== 'hidden_by_admin');
  const completedBorrows = requests.filter((r) => r.requesterId === user.id && r.status === 'completed').length;
  const thankYouNotes = user.thankYouNotes?.length ?? 0;

  const lenderIds = new Set(listings.map((l) => l.ownerId));
  const foundingLenders = users
    .filter((u) => lenderIds.has(u.id) && u.role !== 'admin')
    .sort((a, b) => new Date(a.joinedAt).getTime() - new Date(b.joinedAt).getTime())
    .slice(0, BADGE_THRESHOLDS.foundingLenders)
    .map((u) => u.id);

  const stats: UserProfileStats = {
    itemsShared: user.itemsSharedCount,
    activeListings: ownListings.filter((l) => l.status === 'active').length,
    completedBorrows,
    thankYouNotes,
  };

  const badges: ProfileBadge[] = [
    {
      name: 'founding-lender',
      earned: foundingLenders.includes(user.id),
      rule: `One of the first ${BADGE_THRESHOLDS.foundingLenders} residents to list an item`,
    },
    {
      name: 'helper',
      earned: stats.itemsShared >= BADGE_THRESHOLDS.helperCompletedLoans,
      rule: `${BADGE_THRESHOLDS.helperCompletedLoans} completed loans as a lender`,
    },
    {
      name: 'toolkeeper',
      earned: ownListings.length >= BADGE_THRESHOLDS.toolkeeperListedItems,
      rule: `${BADGE_THRESHOLDS.toolkeeperListedItems} or more items listed`,
    },
    {
      name: 'reliable',
      earned: completedBorrows >= BADGE_THRESHOLDS.reliableCompletedBorrows,
      rule: `${BADGE_THRESHOLDS.reliableCompletedBorrows} borrows returned and completed`,
    },
    {
      name: 'thank-you',
      earned: thankYouNotes > 0,
      rule: 'Received a thank-you note from a neighbour',
    },
    {
      name: 'neighbour-of-month',
      earned: false,
      rule: 'Opt-in monthly recognition (not running in this demo)',
    },
  ];

  return { stats, badges };
}
